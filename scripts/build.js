// Builds /COOKBOOK.md (one file for chat assistants) from /skills/totaljs-cookbook/references/*.md
// Usage: node scripts/build.js

const Fs = require('fs');
const Path = require('path');

const root = Path.join(__dirname, '..');
const dir = Path.join(root, 'skills/totaljs-cookbook/references');
const files = Fs.readdirSync(dir).filter(name => (/^\d\d-.*\.md$/).test(name)).sort();

function anchor(title) {
	return '#' + title.toLowerCase().replace(/`/g, '').replace(/[^a-z0-9 _-]/g, '').replace(/ /g, '-');
}

var sections = [];
var anchors = {};
var about = '';

for (var i = 0; i < files.length; i++) {
	var body = Fs.readFileSync(Path.join(dir, files[i]), 'utf8').trim();
	if (files[i].substring(0, 2) === '00') {
		about = body;
		continue;
	}
	var index = body.indexOf('\n');
	var title = body.substring(2, index).trim();
	anchors[files[i]] = anchor(title);
	sections.push({ title: title, body: body.substring(index + 1).trim() });
}

function links(value) {
	return value.replace(/\]\((\d\d-[a-z0-9-]+\.md)\)/g, function(text, name) {
		if (!anchors[name])
			throw new Error('Unknown link: ' + name);
		return '](' + anchors[name] + ')';
	});
}

var output = [links(about), '', '> Generated by `scripts/build.js` from `skills/totaljs-cookbook/references/`. Do not edit this file by hand.', '', '---', '', '## Contents', ''];

for (var i = 0; i < sections.length; i++) {
	var title = sections[i].title;
	var index = title.indexOf(' ');
	output.push(title.substring(0, index) + ' [' + title.substring(index + 1) + '](' + anchor(title) + ')');
}

for (var i = 0; i < sections.length; i++)
	output.push('', '---', '', '## ' + sections[i].title, '', links(sections[i].body));

Fs.writeFileSync(Path.join(root, 'COOKBOOK.md'), output.join('\n') + '\n');
console.log('COOKBOOK.md: ' + sections.length + ' sections');
